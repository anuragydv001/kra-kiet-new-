from django.db import models
from core.models import Department, KRAMetric
from django.conf import settings

class BiMonthlyCycle(models.Model):
    CYCLE_CHOICES = (
        ('JUL-AUG', 'July - August'),
        ('SEP-OCT', 'September - October'),
        ('NOV-DEC', 'November - December'),
        ('JAN-FEB', 'January - February'),
        ('MAR-APR', 'March - April'),
        ('MAY-JUN', 'May - June'),
    )

    academic_year = models.CharField(max_length=9, help_text="e.g. 2026-2027")
    cycle_name = models.CharField(max_length=20, choices=CYCLE_CHOICES)
    deadline = models.DateField(help_text="Deadline for submission. Emails sent 5 days prior.")
    is_active = models.BooleanField(default=True)

    def __str__(self):
        return f"{self.cycle_name} ({self.academic_year})"
    
    class Meta:
        unique_together = ('academic_year', 'cycle_name')

class CycleException(models.Model):
    cycle = models.ForeignKey(BiMonthlyCycle, on_delete=models.CASCADE, related_name='exceptions')
    department = models.ForeignKey(Department, on_delete=models.CASCADE, related_name='cycle_exceptions', null=True, blank=True, help_text="Leave blank to reopen for all departments.")
    open_until = models.DateField(help_text="The new deadline for this exception.")
    reason = models.TextField(help_text="Reason for reopening.")
    opened_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.SET_NULL, null=True, blank=True)

    def __str__(self):
        dept_name = self.department.name if self.department else "All Departments"
        return f"{self.cycle} reopened for {dept_name} until {self.open_until}"

class Achievement(models.Model):
    STATUS_CHOICES = (
        ('DRAFT', 'Draft'),
        ('SUBMITTED', 'Submitted'),
        ('REJECTED', 'Rejected'),
        ('APPROVED', 'Approved'),
    )

    department = models.ForeignKey(Department, on_delete=models.CASCADE, related_name='achievements')
    kra_metric = models.ForeignKey(KRAMetric, on_delete=models.CASCADE, related_name='achievements')
    cycle = models.ForeignKey(BiMonthlyCycle, on_delete=models.CASCADE, related_name='achievements')
    
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default='DRAFT')
    review_comment = models.TextField(blank=True, null=True, help_text="Comment from Super Admin upon review/rejection.")
    numeric_value = models.DecimalField(max_digits=10, decimal_places=2, null=True, blank=True, help_text="Used for targets with Numeric/Percentage types")
    remarks = models.TextField(blank=True, null=True)
    custom_data = models.JSONField(default=dict, blank=True, help_text="Dynamic per-KRA form fields and uploaded evidence details.")
    
    submitted_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.SET_NULL, null=True, blank=True)
    updated_at = models.DateTimeField(auto_now=True)

    def __str__(self):
        return f"{self.department.name} - {self.kra_metric.serial_number} - {self.cycle.cycle_name}"
    
    @property
    def dynamic_target(self):
        """
        Dynamically calculate the target for this department based on faculty strength.
        Assumes kra_metric.annual_target is a numeric string if it's meant to be multiplied.
        """
        try:
            base_target = float(self.kra_metric.annual_target)
            if self.kra_metric.target_type == 'Numeric':
                # Multiply the base target by the department's faculty strength
                return base_target * self.department.faculty_strength
            return base_target
        except (ValueError, TypeError):
            # If the annual_target is not a number (e.g. "Boolean" or text), just return it as is.
            return self.kra_metric.annual_target
    
    class Meta:
        unique_together = ('department', 'kra_metric', 'cycle')

class Evidence(models.Model):
    achievement = models.ForeignKey(Achievement, on_delete=models.CASCADE, related_name='evidence')
    document_data = models.JSONField(default=dict, help_text="Stores the raw form data input by the faculty for the template.")
    generated_pdf = models.FileField(upload_to='evidence_pdfs/%Y/%m/', blank=True, null=True, help_text="The final PDF generated by the system upon export.")
    last_edited_at = models.DateTimeField(auto_now=True)

    def __str__(self):
        return f"Evidence Data for {self.achievement}"

class UploadedEvidenceFile(models.Model):
    achievement = models.ForeignKey(Achievement, on_delete=models.CASCADE, related_name='uploaded_files')
    document_type = models.CharField(max_length=255, help_text="e.g. Approval/permission for conducting the course")
    file = models.FileField(upload_to='kra_evidence/%Y/%m/')
    filename = models.CharField(max_length=255)
    file_size_kb = models.FloatField(default=0.0)
    uploaded_at = models.DateTimeField(auto_now_add=True)
    uploaded_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.SET_NULL, null=True, blank=True)

    def __str__(self):
        return f"{self.achievement} - {self.document_type}: {self.filename}"

