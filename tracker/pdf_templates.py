from reportlab.pdfgen import canvas
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors

class BasePDFTemplate:
    """ Base class for all KIET KRA PDF Templates """
    def __init__(self, buffer):
        self.buffer = buffer
        self.p = canvas.Canvas(self.buffer, pagesize=letter)
        self.width, self.height = letter

    def draw_header(self, title):
        # Draw College Header Placeholder
        self.p.setFont("Helvetica-Bold", 16)
        self.p.drawString(100, self.height - 50, "KIET GROUP OF INSTITUTIONS")
        self.p.setFont("Helvetica", 12)
        self.p.drawString(100, self.height - 70, "Internal Quality Assurance Cell (IQAC)")
        
        # Draw Document Title
        self.p.setFont("Helvetica-Bold", 14)
        self.p.drawString(100, self.height - 100, title)
        
        # Line separator
        self.p.line(50, self.height - 110, self.width - 50, self.height - 110)

    def draw_footer(self):
        self.p.setFont("Helvetica", 9)
        self.p.drawString(50, 30, "Generated by KIET KRA Tracker System")
        self.p.drawString(self.width - 100, 30, f"Page {self.p.getPageNumber()}")

    def save(self):
        self.draw_footer()
        self.p.showPage()
        self.p.save()

class CountBasedTemplate(BasePDFTemplate):
    def render(self, data):
        self.draw_header(f"Evidence Report: {data.get('kra_title', 'KRA Achievement')}")
        self.p.setFont("Helvetica", 12)
        self.p.drawString(100, self.height - 150, f"Department: {data.get('department', 'N/A')}")
        self.p.drawString(100, self.height - 170, f"Total Count Claimed: {data.get('total_count', '0')}")
        self.p.drawString(100, self.height - 190, f"Remarks: {data.get('remarks', 'None')}")
        self.save()

class FeedbackTemplate(BasePDFTemplate):
    def render(self, data):
        self.draw_header(f"Feedback & Action Taken Report")
        self.p.setFont("Helvetica-Bold", 12)
        
        self.p.drawString(100, self.height - 150, "1. Action Taken:")
        self.p.setFont("Helvetica", 11)
        self.p.drawString(120, self.height - 170, str(data.get('action_taken', 'N/A')))
        
        self.p.setFont("Helvetica-Bold", 12)
        self.p.drawString(100, self.height - 210, "2. Impact Analysis:")
        self.p.setFont("Helvetica", 11)
        self.p.drawString(120, self.height - 230, str(data.get('impact_analysis', 'N/A')))
        
        self.p.setFont("Helvetica-Bold", 12)
        self.p.drawString(100, self.height - 270, "3. Discussion in BoS:")
        self.p.setFont("Helvetica", 11)
        self.p.drawString(120, self.height - 290, str(data.get('bos_discussion', 'N/A')))
        
        self.save()

